"""
src/pest_forecasting/inference.py
─────────────────────────────────
Separate, production-isolated inference interface for experimental
synthetic multi-crop pest outbreak forecasting.
Strictly tagged with SYNTHETIC_EXPERIMENTAL classification and disclaimers.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

import joblib
import pandas as pd
from pydantic import BaseModel, Field, ValidationError

from .dataset import (
    CATEGORICAL_COLUMNS,
    ENVIRONMENTAL_FEATURE_COLUMNS,
    FULL_FEATURE_COLUMNS,
)

MODELS_DIR = Path("models/experimental_synthetic_pest")

SCIENTIFIC_DISCLAIMER = (
    "SYNTHETIC EXPERIMENTAL MODEL ONLY: This score is generated by an experimental model "
    "trained exclusively on synthetic biophysical simulation data. It is NOT a calibrated "
    "real-world outbreak probability and must NOT be used for commercial, legal, or "
    "operational farm management or pesticide spraying decisions."
)


class ExperimentalPestForecastInput(BaseModel):
    """Input payload for experimental 7-day pest outbreak forecast."""
    crop: str = Field(description="Target crop (Maize, Cotton, Rice, Wheat, Tomato, Chickpea)")
    pest: str = Field(description="Target insect pest species")
    district: str = Field(description="Agricultural district")
    growth_stage: str = Field(description="Crop growth / phenological stage")
    t7_mean_temp_c: float = Field(ge=-10.0, le=60.0, description="7-day rolling mean temperature (°C)")
    t7_min_temp_c: float = Field(ge=-15.0, le=50.0, description="7-day minimum temperature (°C)")
    t7_max_temp_c: float = Field(ge=-5.0, le=65.0, description="7-day maximum temperature (°C)")
    t7_mean_rh_pct: float = Field(ge=0.0, le=100.0, description="7-day rolling mean relative humidity (%)")
    t7_high_rh_days: int = Field(ge=0, le=7, description="Count of days in past week with RH >= 80%")
    t7_rainfall_mm: float = Field(ge=0.0, description="7-day cumulative rainfall (mm)")
    t14_rainfall_mm: float = Field(ge=0.0, description="14-day cumulative rainfall (mm)")

    # Optional in-field scouting features (only required for FULL synthetic configuration)
    current_incidence_pct_t0: Optional[float] = Field(default=None, ge=0.0, le=100.0, description="Observed infested plants (%)")
    current_severity_pct_t0: Optional[float] = Field(default=None, ge=0.0, le=100.0, description="Observed tissue damage (%)")
    pest_present_t0: Optional[int] = Field(default=None, ge=0, le=1, description="Binary insect presence indicator (0 or 1)")


class ExperimentalPestForecastOutput(BaseModel):
    """Output prediction response with mandatory experimental labeling."""
    classification: str = "SYNTHETIC_EXPERIMENTAL"
    feature_configuration: str  # "ENVIRONMENTAL_ONLY" or "FULL_SYNTHETIC"
    predicted_outbreak_risk: float  # [0.0, 1.0]
    outbreak_warning: bool
    decision_threshold: float
    model_family: str
    model_version: str
    is_production_ready: bool = False
    disclaimer: str = SCIENTIFIC_DISCLAIMER
    input_summary: dict[str, Any]


class ExperimentalPestForecaster:
    """
    Experimental inference service.
    Kept strictly isolated from production advisory services.
    """

    def __init__(
        self,
        models_dir: Path | str = MODELS_DIR,
        config: str = "environmental",
    ):
        self.models_dir = Path(models_dir)
        self.config = config.lower()
        self.pipeline = None
        self.metadata = {}
        self.threshold = 0.50
        self.best_model_name = "ExperimentalClassifier"
        self._load()

    def _load(self) -> None:
        """Load trained pipeline and metadata."""
        if not self.models_dir.exists():
            return

        pipeline_file = (
            self.models_dir / "environmental_model_pipeline.joblib"
            if self.config in ("environmental", "environmental_only")
            else self.models_dir / "full_model_pipeline.joblib"
        )

        if pipeline_file.exists():
            self.pipeline = joblib.load(pipeline_file)

        summary_file = self.models_dir / "experiment_comparison_summary.json"
        if summary_file.exists():
            try:
                with open(summary_file, "r", encoding="utf-8") as f:
                    self.metadata = json.load(f)
                    cfg_key = "ENVIRONMENTAL_ONLY" if self.config in ("environmental", "environmental_only") else "FULL_SYNTHETIC"
                    cfg_info = self.metadata.get("experiments", {}).get(cfg_key, {})
                    self.best_model_name = cfg_info.get("best_model_name", "BestClassifier")
                    # Retrieve optimal threshold
                    m_data = cfg_info.get("models", {}).get(self.best_model_name, {})
                    self.threshold = m_data.get("optimal_threshold", 0.50)
            except Exception:
                pass

    def predict(
        self,
        input_data: ExperimentalPestForecastInput | dict[str, Any],
    ) -> ExperimentalPestForecastOutput:
        """
        Execute prediction on validated input payload.
        """
        if self.pipeline is None:
            raise RuntimeError(
                f"Experimental model pipeline not found in {self.models_dir}. "
                "Execute training first via `python -m src.pest_forecasting.train`."
            )

        if isinstance(input_data, dict):
            input_obj = ExperimentalPestForecastInput(**input_data)
        else:
            input_obj = input_data

        # Check biological / causal consistency
        if input_obj.t7_min_temp_c > input_obj.t7_max_temp_c:
            raise ValueError("t7_min_temp_c cannot exceed t7_max_temp_c.")
        if input_obj.t7_rainfall_mm > input_obj.t14_rainfall_mm:
            raise ValueError("7-day rainfall cannot exceed 14-day cumulative rainfall.")

        # Prepare DataFrame row
        row_dict = input_obj.model_dump()

        # Check scouting requirement if running FULL mode
        if self.config not in ("environmental", "environmental_only"):
            missing_scout = [
                f for f in ["current_incidence_pct_t0", "current_severity_pct_t0", "pest_present_t0"]
                if row_dict.get(f) is None
            ]
            if missing_scout:
                raise ValueError(
                    f"FULL_SYNTHETIC configuration requires in-field scouting observations. "
                    f"Missing fields: {missing_scout}. Use config='environmental' to run environmental-only."
                )

        # Build feature DataFrame with correct columns
        expected_cols = (
            ENVIRONMENTAL_FEATURE_COLUMNS
            if self.config in ("environmental", "environmental_only")
            else FULL_FEATURE_COLUMNS
        )
        df_row = pd.DataFrame([{col: row_dict.get(col) for col in expected_cols}])

        # Predict probability
        prob = float(self.pipeline.predict_proba(df_row)[0, 1])
        warning = bool(prob >= self.threshold)

        cfg_label = "ENVIRONMENTAL_ONLY" if self.config in ("environmental", "environmental_only") else "FULL_SYNTHETIC"

        return ExperimentalPestForecastOutput(
            classification="SYNTHETIC_EXPERIMENTAL",
            feature_configuration=cfg_label,
            predicted_outbreak_risk=round(prob, 4),
            outbreak_warning=warning,
            decision_threshold=round(self.threshold, 3),
            model_family=self.best_model_name,
            model_version="1.0.0-experimental-synthetic",
            is_production_ready=False,
            disclaimer=SCIENTIFIC_DISCLAIMER,
            input_summary={
                "crop": input_obj.crop,
                "pest": input_obj.pest,
                "district": input_obj.district,
                "growth_stage": input_obj.growth_stage,
                "t7_mean_temp_c": input_obj.t7_mean_temp_c,
                "t7_mean_rh_pct": input_obj.t7_mean_rh_pct,
                "t7_rainfall_mm": input_obj.t7_rainfall_mm,
            },
        )

